DROP TABLE IF EXISTS "sale" CASCADE;
DROP TABLE IF EXISTS "rent" CASCADE;
DROP TABLE IF EXISTS "test_drive" CASCADE;
DROP TABLE IF EXISTS "request" CASCADE;
DROP TABLE IF EXISTS "manager" CASCADE;
DROP TABLE IF EXISTS "salesman" CASCADE;
DROP TABLE IF EXISTS "bank_account" CASCADE;
DROP TABLE IF EXISTS "client" CASCADE;
DROP VIEW IF EXISTS "user" CASCADE;
DROP TABLE IF EXISTS "user" CASCADE;
DROP FUNCTION IF EXISTS check_user_email_disjoint CASCADE;
DROP TABLE IF EXISTS "vehicle_discount" CASCADE;
DROP TABLE IF EXISTS "vehicle" CASCADE;
DROP TABLE IF EXISTS "model_discount" CASCADE;
DROP TABLE IF EXISTS "model" CASCADE;
DROP TABLE IF EXISTS "brand" CASCADE;

-- -----------------------------------------------------------------------------
-- 1. Brand (Marca)
-- -----------------------------------------------------------------------------
CREATE TABLE "brand" (
    "name" VARCHAR(50) NOT NULL,
    CONSTRAINT "pk_brand" PRIMARY KEY ("name")
);

-- -----------------------------------------------------------------------------
-- 2. Model (Modello)
-- -----------------------------------------------------------------------------
CREATE TABLE "model" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "brand" VARCHAR(50) NOT NULL,
    "name" VARCHAR(50) NOT NULL,
    "release_price" DECIMAL(10, 2) NOT NULL,
    "release_year" SMALLINT NOT NULL,
    CONSTRAINT "pk_model" PRIMARY KEY ("id"),
    CONSTRAINT "uq_model_name" UNIQUE ("name"),
    CONSTRAINT "fk_model_brand" FOREIGN KEY ("brand") REFERENCES "brand" ("name") ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT "chk_model_release_price" CHECK ("release_price" >= 0),
    CONSTRAINT "chk_model_release_year" CHECK ("release_year" >= 1900)
);

-- -----------------------------------------------------------------------------
-- 3. ModelDiscount (Sconto per Modello)
-- -----------------------------------------------------------------------------
CREATE TABLE "model_discount" (
    "model" BIGINT NOT NULL,
    "value" SMALLINT NOT NULL,
    CONSTRAINT "pk_model_discount" PRIMARY KEY ("model"),
    CONSTRAINT "fk_model_discount_model" FOREIGN KEY ("model") REFERENCES "model" ("id") ON DELETE CASCADE,
    CONSTRAINT "chk_model_discount_value" CHECK ("value" >= 0 AND "value" <= 50)
);

-- -----------------------------------------------------------------------------
-- 4. Vehicle (Veicolo)
-- -----------------------------------------------------------------------------
CREATE TABLE "vehicle" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "model" BIGINT NOT NULL,
    "vin" VARCHAR(17) NOT NULL,
    "licence_plate" VARCHAR(10),
    "kilometers" INT NOT NULL,
    "price" DECIMAL(10, 2) NOT NULL,
    "year" SMALLINT NOT NULL,
    "state" VARCHAR(50) NOT NULL,
    CONSTRAINT "pk_vehicle" PRIMARY KEY ("id"),
    CONSTRAINT "uq_vehicle_vin" UNIQUE ("vin"),
    CONSTRAINT "uq_vehicle_licence_plate" UNIQUE ("licence_plate"),
    CONSTRAINT "fk_vehicle_model" FOREIGN KEY ("model") REFERENCES "model" ("id") ON DELETE RESTRICT,
    CONSTRAINT "chk_vehicle_price" CHECK ("price" >= 0),
    CONSTRAINT "chk_vehicle_kilometers" CHECK ("kilometers" >= 0),
    CONSTRAINT "chk_vehicle_year" CHECK ("year" >= 1900),
    CONSTRAINT "chk_vehicle_state" CHECK ("state" IN ('SALE', 'RENT', 'BLOCKED', 'WAITING', 'SOLD')),
    CONSTRAINT "chk_vehicle_plate_km" CHECK ("licence_plate" IS NOT NULL OR "kilometers" = 0)
);

-- -----------------------------------------------------------------------------
-- 5. VehicleDiscount (Sconto per Veicolo)
-- -----------------------------------------------------------------------------
CREATE TABLE "vehicle_discount" (
    "vehicle" BIGINT NOT NULL,
    "value" SMALLINT NOT NULL,
    CONSTRAINT "pk_vehicle_discount" PRIMARY KEY ("vehicle"),
    CONSTRAINT "fk_vehicle_discount_vehicle" FOREIGN KEY ("vehicle") REFERENCES "vehicle" ("id") ON DELETE CASCADE,
    CONSTRAINT "chk_vehicle_discount_value" CHECK ("value" >= 0 AND "value" <= 50)
);

-- -----------------------------------------------------------------------------
-- 6. Generalizzazione Utente (Totale e Disgiunta)
-- -----------------------------------------------------------------------------

-- 6a. Client (Cliente)
CREATE TABLE "client" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "name" VARCHAR(50) NOT NULL,
    "surname" VARCHAR(50) NOT NULL,
    "email" VARCHAR(50) NOT NULL,
    "hash_password" VARCHAR(255) NOT NULL,
    CONSTRAINT "pk_client" PRIMARY KEY ("id"),
    CONSTRAINT "uq_client_email" UNIQUE ("email"),
    CONSTRAINT "chk_client_email_fmt" CHECK ("email" LIKE '%_@_%._%')
);

-- 6b. Salesman (Venditore)
CREATE TABLE "salesman" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "name" VARCHAR(50) NOT NULL,
    "surname" VARCHAR(50) NOT NULL,
    "email" VARCHAR(50) NOT NULL,
    "hash_password" VARCHAR(255) NOT NULL,
    CONSTRAINT "pk_salesman" PRIMARY KEY ("id"),
    CONSTRAINT "uq_salesman_email" UNIQUE ("email"),
    CONSTRAINT "chk_salesman_email_fmt" CHECK ("email" LIKE '%_@_%._%')
);

-- 6c. Manager (Dirigente)
CREATE TABLE "manager" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "name" VARCHAR(50) NOT NULL,
    "surname" VARCHAR(50) NOT NULL,
    "email" VARCHAR(50) NOT NULL,
    "hash_password" VARCHAR(255) NOT NULL,
    CONSTRAINT "pk_manager" PRIMARY KEY ("id"),
    CONSTRAINT "uq_manager_email" UNIQUE ("email"),
    CONSTRAINT "chk_manager_email_fmt" CHECK ("email" LIKE '%_@_%._%')
);

-- -----------------------------------------------------------------------------
-- 7. BankAccount (Conto Corrente intestato al Cliente)
-- -----------------------------------------------------------------------------
CREATE TABLE "bank_account" (
    "iban" VARCHAR(27) NOT NULL,
    "client" BIGINT NOT NULL,
    "balance" DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT "pk_bank_account" PRIMARY KEY ("iban"),
    CONSTRAINT "uq_bank_account_client" UNIQUE ("client"),
    CONSTRAINT "fk_bank_account_client" FOREIGN KEY ("client") REFERENCES "client" ("id") ON DELETE CASCADE,
    CONSTRAINT "chk_bank_account_balance" CHECK ("balance" >= 0)
);

-- -----------------------------------------------------------------------------
-- Vincolo di Disgiunzione (d): Trigger per unicità globale dell'email tra i ruoli
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_user_email_disjoint()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_TABLE_NAME <> 'client' AND EXISTS (SELECT 1 FROM "client" WHERE "email" = NEW."email" AND "id" <> COALESCE(NEW."id", -1)) THEN
        RAISE EXCEPTION 'Violazione vincolo di disgiunzione (d): l''email % appartiene già a un cliente.', NEW."email";
    END IF;
    IF TG_TABLE_NAME <> 'salesman' AND EXISTS (SELECT 1 FROM "salesman" WHERE "email" = NEW."email" AND "id" <> COALESCE(NEW."id", -1)) THEN
        RAISE EXCEPTION 'Violazione vincolo di disgiunzione (d): l''email % appartiene già a un venditore.', NEW."email";
    END IF;
    IF TG_TABLE_NAME <> 'manager' AND EXISTS (SELECT 1 FROM "manager" WHERE "email" = NEW."email" AND "id" <> COALESCE(NEW."id", -1)) THEN
        RAISE EXCEPTION 'Violazione vincolo di disgiunzione (d): l''email % appartiene già a un manager.', NEW."email";
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS "trg_client_disjoint_email" ON "client";
CREATE TRIGGER "trg_client_disjoint_email"
BEFORE INSERT OR UPDATE OF "email" ON "client"
FOR EACH ROW EXECUTE FUNCTION check_user_email_disjoint();

DROP TRIGGER IF EXISTS "trg_salesman_disjoint_email" ON "salesman";
CREATE TRIGGER "trg_salesman_disjoint_email"
BEFORE INSERT OR UPDATE OF "email" ON "salesman"
FOR EACH ROW EXECUTE FUNCTION check_user_email_disjoint();

DROP TRIGGER IF EXISTS "trg_manager_disjoint_email" ON "manager";
CREATE TRIGGER "trg_manager_disjoint_email"
BEFORE INSERT OR UPDATE OF "email" ON "manager"
FOR EACH ROW EXECUTE FUNCTION check_user_email_disjoint();

-- Vista unificata "user" per agevolare query globali o autenticazione
CREATE OR REPLACE VIEW "user" AS
    SELECT "id", "name", "surname", "email", "hash_password", 'CLIENT' AS "role" FROM "client"
    UNION ALL
    SELECT "id", "name", "surname", "email", "hash_password", 'SALESMAN' AS "role" FROM "salesman"
    UNION ALL
    SELECT "id", "name", "surname", "email", "hash_password", 'MANAGER' AS "role" FROM "manager";

-- -----------------------------------------------------------------------------
-- 8. Request (Richiesta di acquisto o di vendita auto cliente)
-- -----------------------------------------------------------------------------
CREATE TABLE "request" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "vehicle" BIGINT NOT NULL,
    "client" BIGINT NOT NULL,
    "salesman" BIGINT,
    "deposit" DECIMAL(10, 2) NOT NULL,
    "exp_date" DATE,
    CONSTRAINT "pk_request" PRIMARY KEY ("id"),
    CONSTRAINT "fk_request_vehicle" FOREIGN KEY ("vehicle") REFERENCES "vehicle" ("id") ON DELETE RESTRICT,
    CONSTRAINT "fk_request_client" FOREIGN KEY ("client") REFERENCES "client" ("id") ON DELETE RESTRICT,
    CONSTRAINT "fk_request_salesman" FOREIGN KEY ("salesman") REFERENCES "salesman" ("id") ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- 9. TestDrive (Prenotazione giro di prova)
-- -----------------------------------------------------------------------------
CREATE TABLE "test_drive" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "vehicle" BIGINT NOT NULL,
    "client" BIGINT NOT NULL,
    "date" TIMESTAMP NOT NULL,
    CONSTRAINT "pk_test_drive" PRIMARY KEY ("id"),
    CONSTRAINT "fk_test_drive_vehicle" FOREIGN KEY ("vehicle") REFERENCES "vehicle" ("id") ON DELETE RESTRICT,
    CONSTRAINT "fk_test_drive_client" FOREIGN KEY ("client") REFERENCES "client" ("id") ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- 10. Rent (Noleggio)
-- -----------------------------------------------------------------------------
CREATE TABLE "rent" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "vehicle" BIGINT NOT NULL,
    "client" BIGINT NOT NULL,
    "amount" DECIMAL(10, 2) NOT NULL,
    "start" DATE NOT NULL,
    "end" DATE NOT NULL,
    CONSTRAINT "pk_rent" PRIMARY KEY ("id"),
    CONSTRAINT "fk_rent_vehicle" FOREIGN KEY ("vehicle") REFERENCES "vehicle" ("id") ON DELETE RESTRICT,
    CONSTRAINT "fk_rent_client" FOREIGN KEY ("client") REFERENCES "client" ("id") ON DELETE RESTRICT,
    CONSTRAINT "chk_rent_amount" CHECK ("amount" >= 0),
    CONSTRAINT "chk_rent_dates" CHECK ("end" >= "start")
);

-- -----------------------------------------------------------------------------
-- 11. Sale (Registro compravendite e penali)
-- -----------------------------------------------------------------------------
CREATE TABLE "sale" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "vehicle" BIGINT,
    "salesman" BIGINT,
    "client" BIGINT NOT NULL,
    "amount" DECIMAL(10, 2) NOT NULL,
    "date" TIMESTAMP NOT NULL,
    CONSTRAINT "pk_sale" PRIMARY KEY ("id"),
    CONSTRAINT "fk_sale_vehicle" FOREIGN KEY ("vehicle") REFERENCES "vehicle" ("id") ON DELETE SET NULL,
    CONSTRAINT "fk_sale_salesman" FOREIGN KEY ("salesman") REFERENCES "salesman" ("id") ON DELETE SET NULL,
    CONSTRAINT "fk_sale_client" FOREIGN KEY ("client") REFERENCES "client" ("id") ON DELETE RESTRICT
);
